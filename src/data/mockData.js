// Generate chart history points for different timeframes (1D, 1W, 1M, 1Y, ALL)
const generateHistory = (basePrice, trend = 'up', volatility = 0.02) => {
  const timeframes = {
    '1D': 16, // intraday
    '1W': 7,  // daily
    '1M': 30, // daily
    '1Y': 12, // monthly
    'ALL': 24 // bi-monthly
  };

  const labels = {
    '1D': ['9:30 AM', '10:00 AM', '10:30 AM', '11:00 AM', '11:30 AM', '12:00 PM', '12:30 PM', '1:00 PM', '1:30 PM', '2:00 PM', '2:30 PM', '3:00 PM', '3:30 PM', '4:00 PM'],
    '1W': ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Today'],
    '1M': ['W1', 'W2', 'W3', 'W4', 'W5', 'W6'],
    '1Y': ['Jan', 'Mar', 'May', 'Jul', 'Sep', 'Nov', 'Now'],
    'ALL': ['2020', '2021', '2022', '2023', '2024', '2025', '2026']
  };

  const data = {};

  Object.entries(timeframes).forEach(([tf, points]) => {
    let currentPrice = basePrice * (trend === 'up' ? 0.93 : 1.07);
    const series = [];
    const labelSet = labels[tf];

    for (let i = 0; i < points; i++) {
      const deltaPercent = (Math.random() - (trend === 'up' ? 0.44 : 0.56)) * volatility;
      currentPrice = +(currentPrice * (1 + deltaPercent)).toFixed(2);
      
      const high = +(currentPrice * (1 + Math.random() * 0.012)).toFixed(2);
      const low = +(currentPrice * (1 - Math.random() * 0.012)).toFixed(2);
      const open = +(low + Math.random() * (high - low)).toFixed(2);
      const volume = Math.floor(1200000 + Math.random() * 4800000);
      const sma20 = +(currentPrice * 0.992).toFixed(2);
      const rsi = Math.floor(42 + Math.random() * 32);

      const label = labelSet[i % labelSet.length] + (points > labelSet.length ? ` #${Math.floor(i / labelSet.length) + 1}` : '');

      series.push({
        time: label,
        price: currentPrice,
        open,
        high,
        low,
        close: currentPrice,
        volume,
        sma20,
        rsi
      });
    }

    // Ensure the last point matches the basePrice
    series[series.length - 1].price = basePrice;
    series[series.length - 1].close = basePrice;

    data[tf] = series;
  });

  return data;
};

